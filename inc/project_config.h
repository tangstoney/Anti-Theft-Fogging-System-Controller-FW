#ifndef RD91_PROJECT_CONFIG_H
#define RD91_PROJECT_CONFIG_H

#define RD91_ROLE "controller"

/*
 * ==========================================================================
 * QMI8A01z 传感器配置
 * --------------------------------------------------------------------------
 * 分三组：
 *   1) 公共采样：两条检测链路共用同一份样本流，必须先定下来；
 *   2) 硬件 Any-Motion：只管“扰动唤醒”，不是冲击峰值，也不是行驶判断；
 *   3) 软件两条链路：运动状态（秒级振动统计）与疑似冲击（逐样本峰值）。
 *
 * 全部是台架实验值，没有已经确定的产品指标。
 * 手册页码为 PDF 页码（QMI8A01z Datasheet Rev A）。
 * ==========================================================================
 */

/* -------------------- 1) 公共采样：量程、ODR、滤波、总线 -------------------- */

/* I2C 从机地址（7 位，不含读写位）。
 * 手册 §1.6 / p8：SA0 接高或悬空 = 0x6A，SA0 接低 = 0x6B。
 * 读不到 ID 时优先怀疑这里。 */
#define RD91_IMU_I2C_ADDR7            0x6AU

/* I2C1 总线速率（Hz）。手册支持 400kHz。
 * 软件采样是 100Hz（10ms 一次，见 RD91_IMU_SAMPLE_PERIOD_TICKS），
 * 100kHz 下读一帧 13 字节约 1.3ms，本来也够用；这里用 400kHz 只是
 * 缩短单次阻塞时间、给以后提高采样率留余量。
 * 杜邦线过长或出现 NACK/总线错误时，先降回 100000 再排查接线。 */
#define RD91_I2C1_CLK_HZ              400000U

/* 加速度量程：0=±2g，1=±4g，2=±8g，3=±16g（手册表 23 CTRL2.aFS，p22）。
 * 选 ±8g：冲击事件需要看 2g 以上的峰值，±2g 会频繁削顶；
 * ±8g 的 1 LSB = 1000/4096 ≈ 0.244mg，分辨率仍远小于振动阈值。
 * 调小 → 分辨率更高但更容易饱和；调大 → 不易削顶但噪声变大。 */
#define RD91_IMU_ACCEL_FS_CODE        2U

/* 加速度 ODR（手册表 23 CTRL2.aODR，p23）。仅开加速度计时：
 * 3=1000Hz，4=500，5=250，6=125，7=62.5，8=31.25；12~15 是低功耗档。
 *
 * 保持 1000Hz 而不是降到 100Hz 的理由：
 *   - 硬件的 Any-Motion 唤醒按 ODR 工作，ODR 越高，扰动到中断的延迟越短；
 *   - 软件每 10ms 只取一个样本，但取到的是芯片最新样本。ODR 高于软件
 *     采样率时，每次读到的样本相位不同，碰上窄冲击尖峰的概率比
 *     “芯片先在 100Hz 上把尖峰平均掉”更高。
 * 代价是芯片本身耗电更高，量产停车态的低功耗档要等实测功耗后再选。
 * 改这里必须同步改 RD91_IMU_ODR_HZ，否则样本计数差值会解释错。 */
#define RD91_IMU_ACCEL_ODR_CODE       3U

/* 与上面 ODR 档位对应的采样率（Hz）。用于解释芯片样本计数的增量。 */
#define RD91_IMU_ODR_HZ               1000U

/* 软件采样线程周期，单位 tick。工程 tick = 10ms（RT_TICK_PER_SECOND=100），
 * 所以 1 tick = 10ms，即 100Hz 软件采样。这是两条链路共同的数据节奏：
 *   - 运动链路：每秒约 100 个样本参与 RMS 统计；
 *   - 冲击链路：峰值的能见时间分辨率是 10ms，见下方说明。
 * 调小（提高采样率）需要同时提高 tick 频率或改用定时器，属于后续工作。 */
#define RD91_IMU_SAMPLE_PERIOD_TICKS  1U

/* 加速度低通滤波（手册表 25 CTRL5，p24）。
 * 0 = 关闭。默认关闭的理由：两条链路共用同一份样本，而冲击检测需要
 * 保留短促尖峰；芯片 LPF 在 1000Hz 下最宽档也只有 13.37%×1000 ≈ 134Hz，
 * 开启会进一步削弱几毫秒级的冲击峰。运动状态需要平滑时，
 * 由它自己的 1 秒窗口 RMS 完成，不在这里压。
 * 若要试开启：1=开，MODE 0/1/2/3 = 2.66/3.63/5.39/13.37%×ODR。 */
#define RD91_IMU_ACCEL_LPF_EN         0U
#define RD91_IMU_ACCEL_LPF_MODE       3U

/* -------------------- 2) 硬件 Any-Motion：只用于扰动唤醒 -------------------- */

/* Any-Motion 三轴阈值，单位 LSB，步进 1/32 g（手册表 36，p43-p44）。
 * 2 LSB = 2 × 0.03125g = 0.0625g。
 * 它判断的是“相邻两个采样的加速度差”，不是总模长、不是峰值。
 * 台架实验值，偏灵敏：调大 → 需要更大扰动才产生中断；调小 → 静置噪声也可能触发。 */
#define RD91_IMU_ANYM_THR_X_LSB       2U
#define RD91_IMU_ANYM_THR_Y_LSB       2U
#define RD91_IMU_ANYM_THR_Z_LSB       2U

/* 连续多少个超阈值采样才置位（手册表 36 AnyMotionWindow，单位 1 样本）。
 * 1 = 第一个超阈值样本就触发；检测时间 ≈ N / ODR。 */
#define RD91_IMU_ANYM_WINDOW_SAMPLES  1U

/* 参与唤醒检测的轴：bit0=X，bit1=Y，bit2=Z（手册表 37，p45）。 */
#define RD91_IMU_ANYM_AXIS_EN         0x07U

/* 0 = OR（任一轴满足），1 = AND（三轴同时满足）。台架用 OR。 */
#define RD91_IMU_ANYM_AXIS_LOGIC_AND  0U

/* Any-Motion 中断事件的日志限流（ms）。
 * 持续扰动时芯片可每秒置位上千次，逐次上报会塞满消息队列；
 * 这段时间内的边沿仍然计数，只是合并成一条日志。 */
#define RD91_IMU_WAKE_REPORT_MIN_MS   200U

/* CTRL9 命令等待 CmdDone 的超时（毫秒）。手册 §5.10 要求有完成确认。 */
#define RD91_IMU_CTRL9_TIMEOUT_MS     50U

/* -------------------- 3a) 运动状态：秒级振动统计 -------------------- */

/* 统计窗口长度（ms）。停车时窗口内只有一个很小的噪声底；
 * 行驶时是持续的不规则振动。100Hz 采样下 1 秒约 100 个样本。 */
#define RD91_MOTION_WINDOW_MS         1000U

/* 一个窗口至少要有多少有效样本才参与判断。
 * 100Hz 采样下 1 秒名义上约 100 个；读取与芯片更新重叠时，一致性复核会丢弃
 * 整帧（见 Imu_ReadFrame），所以实际会低于 100。取 40 是“故障/缺样”的下限：
 * 低于它说明读取大面积失败，直接判 UNKNOWN，绝不累计为“停车”。 */
#define RD91_MOTION_MIN_VALID_SAMPLES 40U

/* 进入“行驶”的振动 RMS 阈值（mg）。RMS 已去掉重力分量：
 * 停车时通常只有几十 mg 的噪声底，正常行驶应明显高于此值。
 * 调小 → 更容易判为行驶；调大 → 更容易判为停车（也更容易漏判低速行驶）。 */
#define RD91_MOTION_ENTER_RMS_MG      150U

/* 退出“行驶”回到“停车”的振动 RMS 阈值（mg）。
 * 必须小于进入阈值，两个阈值形成迟滞，避免在阈值附近来回跳。
 * 调大 → 更难回到停车；调小 → 更容易回到停车。 */
#define RD91_MOTION_EXIT_RMS_MG       80U

/* 连续多少个窗口满足条件才切换状态。默认进入要 2 秒、退出要 3 秒，
 * 单次冲击最多影响一个窗口，因而不能只靠一次扰动把状态改成行驶。 */
#define RD91_MOTION_ENTER_WINDOWS     2U
#define RD91_MOTION_EXIT_WINDOWS      3U

/* 一个窗口内 I2C 错误达到多少次判为 FAULT（传感器故障）。
 * 少量错误不影响判断，但缺样/故障绝不能被当成“停车”的证据。 */
#define RD91_MOTION_FAULT_ERRORS      10U

/* -------------------- 3b) 疑似冲击：逐样本峰值 -------------------- */

/* 进入冲击事件的阈值，单位 mg，指标是“三轴合矢量 |a|”。
 * 静止时 |a| ≈ 1000mg（重力），所以 2000mg 表示总模长达到 2.0g。
 * 注意：|a| 含重力，不能把它当成“冲击加速度本身”。
 * 调高 → 只保留更猛烈的撞击；调低 → 路面颠簸也会进入事件。 */
#define RD91_SHOCK_ENTER_MG           2000U

/* 冲击事件回落阈值（mg）。|a| 低于它并持续 END_GAP 才算事件结束，
 * 避免一次撞击因抖动被拆成几十个事件。
 * 调高 → 事件更快结束；调低 → 余振会被算进同一次事件。 */
#define RD91_SHOCK_RELEASE_MG         1400U

/* 回落多久（ms）后结束事件。软件采样周期 10ms，所以 20ms 约合 2 个样本。 */
#define RD91_SHOCK_END_GAP_MS         20U

/* 事件最长持续时间（ms），防止持续剧烈振动时事件永不结束。
 * 到时限强制输出并重新开始，保证每次输出都有边界。 */
#define RD91_SHOCK_MAX_EVENT_MS       2000U

/* -------------------- 4) 调试日志 -------------------- */

/* 1 = 每个运动统计窗口打印一行（约 1 秒一行）。
 * 0 = 关闭，只保留状态变化和冲击事件日志。 */
#define RD91_IMU_DEBUG_STATS          1U

#endif /* RD91_PROJECT_CONFIG_H */

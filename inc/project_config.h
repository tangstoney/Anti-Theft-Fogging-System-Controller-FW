/* 台架自检：1 = 允许调试器调用 Bench_BatterySimSet() 模拟电量百分比。
 * 0 = 只按真实 I2C 读取（没有电量计时读失败，上报“未知”）。 */
#define RD91_BENCH_BATT_SELFTEST      0U

/* 电量采样周期（ms）。SOC 变化慢，2 秒一次足够；单次读取约 1ms（5 条事务）。 */
#define RD91_BATT_POLL_MS             2000U

/* 连续多久没有成功读取就把百分比标为未知（ms）。取 3 个采样周期：
 * 单次抖动不影响显示，持续失败（断线/器件掉电）必须报未知而不是旧值。 */
#define RD91_BATT_STALE_MS            6000U

/* 正常读取时日志的最小间隔（ms）。状态变化（百分比/有效性/充电标志）立即打印。 */
#define RD91_BATT_LOG_MS              10000U

#if (RD91_BATT_POLL_MS == 0U) || (RD91_BATT_STALE_MS <= RD91_BATT_POLL_MS)
#error "电量采样周期不能为 0，且过期时间必须大于采样周期"
#endif

